/** @type {import('../src/app/models/billing-sov-import.types.ts').BillingSovLineRow[]} */
const sovLines = [];

/**
 * @param {string} job
 * @param {string} payApp
 * @param {number} lineNo
 * @param {Record<string, unknown>} fields
 */
function sov(job, payApp, lineNo, fields) {
  sovLines.push({
    jobNumber: job,
    projectName: PROJECT_NAMES.get(job),
    payAppNumber: payApp,
    lineNumber: lineNo,
    costCode: fields.costCode ?? '',
    description: fields.description ?? '',
    scheduledValue: fields.scheduledValue,
    previousCompleted: fields.previousCompleted ?? 0,
    thisPeriod: fields.thisPeriod ?? 0,
    storedMaterials: fields.storedMaterials ?? 0,
    totalCompleted: fields.totalCompleted ?? fields.totalCompletedStored,
    percentComplete: fields.percentComplete,
    balanceToFinish: fields.balanceToFinish,
    retainage: fields.retainage ?? 0,
    categoryGuess: fields.categoryGuess ?? '',
    sourceFileName: fields.sourceFileName ?? '',
    confidence: fields.confidence ?? 'High',
    reviewNote: fields.reviewNote ?? '',
  });
}

